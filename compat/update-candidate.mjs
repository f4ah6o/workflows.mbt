// Emits a verified update candidate when the latest oracle is compatible —
// and an explicit non-candidate record when it is not.
//
//   node compat/update-candidate.mjs [--oracle latest]
//
// Reads compat-results/verdict-<oracle>.json and candidate-<oracle>.json and
// writes compat-results/update-candidate-<oracle>.json plus, when the verdict
// is `compatible`, compat-results/proposed-manifest.json.
//
// Policy:
//   - compatible: propose the observed upstream tuple as the new pinned
//     baseline. Alongside proposed-manifest.json the run prepares an
//     isolated apply bundle under compat-results/update-candidate-apply/
//     (repo's package.json with the pinned devDependencies updated, the
//     proposed manifest, and package-lock.json regenerated by
//     `npm install --package-lock-only` inside the copy — the repo's
//     working tree is never touched) plus a reviewable unified diff at
//     compat-results/update-candidate.patch. Applying the patch and
//     re-running the pinned suite is a manual, reviewable step; CI never
//     promotes it.
//   - contract-drift / semantic-drift / incomplete-evidence: no pin proposal.
//     The output points at the drift record packet and marks
//     requiresImplementationChange — a fix must land and re-verify before the
//     baseline can move.
//   - upstream-acquisition-failure / upstream-execution-failure /
//     hosted-not-performed: no pin proposal; upstream instability never moves
//     the baseline.
//   - compatibility_date changes are deliberately not bundled: the proposal
//     carries the candidate's pin tuple only, and the reviewer decides on the
//     compatibilityDate bump separately.

import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { resultsDirFor } from "./candidate.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const resultsDir = resultsDirFor(root);
mkdirSync(resultsDir, { recursive: true });
const oracleIndex = process.argv.indexOf("--oracle");
const oracle = oracleIndex >= 0 ? process.argv[oracleIndex + 1] : "latest";

function load(name) {
  const path = join(resultsDir, name);
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
}

// Prepares a reviewable apply bundle in an isolated directory under the
// results dir — the repo working tree is never modified. The bundle is the
// repo's package.json with the pinned devDependencies set to the candidate
// tuple, the proposed manifest at its real path, and package-lock.json
// regenerated by `npm install --package-lock-only` inside the copy. A
// unified diff against the repo files is written to
// compat-results/update-candidate.patch so the change applies with
// `git apply`. Lockfile regeneration failure is recorded honestly and the
// bundle is still emitted (patch then lacks a lockfile hunk).
function buildApplyBundle(proposed, candidate) {
  const applyDir = join(resultsDir, "update-candidate-apply");
  rmSync(applyDir, { recursive: true, force: true });
  mkdirSync(join(applyDir, "compat/oracle"), { recursive: true });

  // Edit the pinned devDependencies on the raw package.json text so the
  // patch carries only the version changes — a full JSON re-serialization
  // would diff every escaped character as unrelated churn.
  const pkgText = readFileSync(join(root, "package.json"), "utf8");
  const pkg = JSON.parse(pkgText);
  const pins = {
    wrangler: candidate.versions.wrangler,
    "@cloudflare/workers-types": candidate.versions.workersTypes,
    workerd: candidate.versions.workerd,
  };
  let appliedPkgText = pkgText;
  for (const [name, version] of Object.entries(pins)) {
    const current = pkg.devDependencies?.[name];
    if (current == null) {
      return { status: "failed", error: `devDependency ${name} missing from package.json` };
    }
    const needle = `"${name}": "${current}"`;
    if (!appliedPkgText.includes(needle)) {
      return { status: "failed", error: `pinned spec ${needle} not found in package.json` };
    }
    appliedPkgText = appliedPkgText.replace(needle, `"${name}": "${version}"`);
  }
  writeFileSync(join(applyDir, "package.json"), appliedPkgText);
  writeFileSync(join(applyDir, "compat/oracle/manifest.json"), JSON.stringify(proposed, null, 2) + "\n");
  copyFileSync(join(root, "package-lock.json"), join(applyDir, "package-lock.json"));

  const npm = process.platform === "win32" ? "npm.cmd" : "npm";
  const install = spawnSync(npm, ["install", "--package-lock-only", "--no-audit", "--no-fund"], {
    cwd: applyDir,
    encoding: "utf8",
  });
  const lockfile = install.status === 0 ? "regenerated" : "failed";

  // Unified diff per file, headers rewritten to a/<rel>/b/<rel> so the
  // patch applies at the repo root with `git apply`.
  const relPaths = ["package.json", "package-lock.json", "compat/oracle/manifest.json"];
  const hunks = [];
  for (const rel of relPaths) {
    const diff = spawnSync("git", ["diff", "--no-index", "--",
      join(root, rel), join(applyDir, rel)], { cwd: root, encoding: "utf8" });
    if (diff.status === 0) continue;
    if (diff.status !== 1 || !diff.stdout) {
      return {
        status: "failed",
        error: "git diff --no-index failed for " + rel + ": " + (diff.stderr || diff.status),
      };
    }
    const rewritten = diff.stdout.split("\n").map((line) => {
      if (line.startsWith("diff --git ")) return `diff --git a/${rel} b/${rel}`;
      if (line.startsWith("--- ")) return `--- a/${rel}`;
      if (line.startsWith("+++ ")) return `+++ b/${rel}`;
      return line;
    }).join("\n");
    hunks.push(rewritten.endsWith("\n") ? rewritten : rewritten + "\n");
  }
  const patchPath = join(resultsDir, "update-candidate.patch");
  writeFileSync(patchPath, hunks.join(""));

  const result = {
    status: "generated",
    dir: "compat-results/update-candidate-apply",
    patch: "compat-results/update-candidate.patch",
    lockfile,
    files: relPaths.filter((rel) => existsSync(join(applyDir, rel))),
  };
  if (lockfile === "failed") {
    result.error = "npm install --package-lock-only failed in the isolated copy"
      + ": " + (install.error?.message ?? install.stderr?.trim().split("\n").at(-1) ?? "exit " + install.status);
  }
  return result;
}

const verdict = load(`verdict-${oracle}.json`);
const candidate = load(`candidate-${oracle}.json`);
const manifest = JSON.parse(readFileSync(join(root, "compat/oracle/manifest.json"), "utf8"));

const outPath = join(resultsDir, `update-candidate-${oracle}.json`);
const now = new Date().toISOString();

let record;
if (!verdict) {
  record = { status: "no-update", reason: "no verdict file — run `npm run compat:latest` first" };
} else if (verdict.verdict === "compatible" && candidate?.status === "ok") {
  const proposed = {
    ...manifest,
    wrangler: candidate.versions.wrangler,
    workersTypes: candidate.versions.workersTypes,
    workerd: candidate.versions.workerd,
    verifiedAt: now.slice(0, 10),
  };
  writeFileSync(join(resultsDir, "proposed-manifest.json"), JSON.stringify(proposed, null, 2) + "\n");
  const apply = buildApplyBundle(proposed, candidate);
  record = {
    status: "proposed",
    reason: "latest oracle compatible — pinned baseline update candidate generated",
    proposed: {
      wrangler: candidate.versions.wrangler,
      "@cloudflare/workers-types": candidate.versions.workersTypes,
      workerd: candidate.versions.workerd,
    },
    current: {
      wrangler: manifest.wrangler,
      "@cloudflare/workers-types": manifest.workersTypes,
      workerd: manifest.workerd,
    },
    changed: manifest.wrangler !== candidate.versions.wrangler
      || manifest.workersTypes !== candidate.versions.workersTypes
      || manifest.workerd !== candidate.versions.workerd,
    proposalFile: "compat-results/proposed-manifest.json",
    apply,
    applySteps: apply.status === "generated" ? [
      "review compat-results/update-candidate.patch",
      "git apply compat-results/update-candidate.patch",
      ...(apply.lockfile === "regenerated"
        ? ["npm ci"]
        : ["npm install --package-lock-only  # patch has no lockfile hunk — regenerate, then npm ci"]),
      "npm run compat:pinned && npm test  # re-verify under the new pin",
      "open a PR — never auto-merge",
    ] : [
      "apply bundle generation failed: " + (apply.error ?? "unknown"),
      "review compat-results/proposed-manifest.json and regenerate manually",
    ],
    verdict: verdict.verdict,
    runId: verdict.runId,
    candidateId: candidate.id,
  };
} else if (["contract-drift", "semantic-drift", "incomplete-evidence"].includes(verdict?.verdict)) {
  record = {
    status: "blocked",
    requiresImplementationChange: true,
    reason: `verdict ${verdict.verdict} — fix and re-verify before the baseline can move`,
    driftPacket: "compat-results/drift-*.md",
    verdict: verdict.verdict,
    issues: verdict.issues ?? [],
  };
} else {
  record = {
    status: "no-update",
    reason: `verdict ${verdict?.verdict} — upstream-side failure/omission never moves the baseline`,
    verdict: verdict?.verdict ?? null,
    issues: verdict?.issues ?? [],
  };
}

record.oracle = oracle;
record.generatedAt = now;
writeFileSync(outPath, JSON.stringify(record, null, 2) + "\n");
console.log(JSON.stringify(record, null, 2));
